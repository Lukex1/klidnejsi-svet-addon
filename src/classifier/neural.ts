export function pointsFromMargin(margin: number): number {
  const scaled = (margin - 0.02) / 0.18;
  if (!Number.isFinite(scaled)) return 0;
  return Math.max(0, Math.min(100, Math.round(scaled * 100)));
}

function dot(left: Float32Array, right: Float32Array): number {
  const length = Math.min(left.length, right.length);
  let sum = 0;
  for (let index = 0; index < length; index += 1) sum += (left[index] ?? 0) * (right[index] ?? 0);
  return sum;
}

function bestDot(vector: Float32Array, bank: readonly Float32Array[]): number {
  let best = -1;
  for (const item of bank) best = Math.max(best, dot(vector, item));
  return best;
}

export function scoresFromVectors(
  post: Float32Array,
  calm: readonly Float32Array[],
  categories: Record<CategoryId, readonly Float32Array[]>,
): Scores {
  const scores = emptyScores();
  const calmScore = bestDot(post, calm);
  for (const id of CATEGORY_IDS) {
    const bank = categories[id];
    scores[id] = pointsFromMargin(bestDot(post, bank) - calmScore);
  }
  return scores;
}
